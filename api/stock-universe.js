const {createClient}=require('@supabase/supabase-js')
const {getAuth}=require('./_lib/auth')
const {rateLimit}=require('./_lib/rateLimit')

module.exports=async function handler(req,res) {
  res.setHeader('Access-Control-Allow-Origin','https://www.optionsedgeflow.com')
  res.setHeader('Access-Control-Allow-Methods','GET,OPTIONS')
  res.setHeader('Access-Control-Allow-Headers','Authorization,Content-Type')
  if(req.method==='OPTIONS') return res.status(204).end()
  if(req.method!=='GET') return res.status(405).json({error:'Method not allowed'})
  const {clerkId,allowed,error}=await getAuth(req)
  if(!clerkId) return res.status(401).json({error:error||'Unauthorized'})
  if(!allowed) return res.status(402).json({error:'An active subscription is required.'})
  const limited=await rateLimit(`stock-universe:${clerkId}`,30,60)
  if(!limited.allowed) return res.status(429).json({error:'Stock universe request limit reached.'})
  const client=createClient(process.env.SUPABASE_URL,process.env.SUPABASE_SERVICE_ROLE_KEY)
  const {data:latest,error:dateError}=await client.from('stock_universe_snapshots').select('snapshot_date').eq('eligible',true).order('snapshot_date',{ascending:false}).limit(1).maybeSingle()
  if(dateError) return res.status(500).json({error:dateError.message})
  if(!latest?.snapshot_date) return res.status(200).json({snapshotDate:null,total:0,results:[],status:'BUILDING'})
  const limit=Math.max(10,Math.min(100,Number(req.query.limit)||50))
  const {data,count,error:queryError}=await client.from('stock_universe_snapshots')
    .select('ticker,company_name,sector,industry,price,average_volume,market_cap,pe_ratio,earnings_date,fundamental_state,fundamental_score,fundamental_coverage,technical_state,technical_score,edge_score,rating,setup,volume_ratio,sma_20,sma_50,support,resistance,entry_low,entry_high,stop_price,target_price,analysis_reason,updated_at',{count:'exact'})
    .eq('snapshot_date',latest.snapshot_date).eq('eligible',true).order('rating',{ascending:true}).order('edge_score',{ascending:false}).limit(limit)
  if(queryError) return res.status(500).json({error:queryError.message})
  return res.status(200).json({snapshotDate:latest.snapshot_date,total:count||0,results:data||[],status:'READY',methodology:'Nightly technical snapshot with live quote overlay; price >= $5, average volume >= 500k, fundamental coverage >= 75%, fundamental score >= 65.'})
}
